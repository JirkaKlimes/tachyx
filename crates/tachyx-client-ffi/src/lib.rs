//! The Dart boundary.
//!
//! `flutter_rust_bridge` generates the two halves of the crossing: the Rust half
//! into [`frb_generated`], the Dart half into the Flutter application. Both are
//! written by the code generator and neither is edited by hand.
//!
//! This crate is deliberately thin. It cannot carry `forbid(unsafe_code)`,
//! because every call across the boundary reads a pointer that Dart wrote, so
//! anything with a decision in it belongs in `tachyx-client` where the ban still
//! holds and where a test needs no Dart runtime to reach it.

pub mod api;

#[allow(
    unreachable_pub,
    missing_docs,
    missing_debug_implementations,
    clippy::pedantic,
    reason = "generated by flutter_rust_bridge; not ours to document or shape"
)]
mod frb_generated;
